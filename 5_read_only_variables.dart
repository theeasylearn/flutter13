// concept of read only variables 
void main()
{
    const NAME = "THE EASYLEARN ACADEMY"; //without type
    const int YEAR = 2026; //with type

    final PI = 3.141516; //without type
    final bool isMarried = true;  //with type

    print(NAME);
    print(YEAR);
    print(PI);
    print(isMarried);

}